def render_tag_list(tags: Iterable[str]) -> None:
    """Render a simple wrapped list of text tags.

    Args:
        tags: Tag labels to render.
    """
    tag_markup = "".join(f'<span class="soc-tag">{escape(tag)}</span>' for tag in tags)
    render_html_block(f'<div class="soc-tag-list">{tag_markup}</div>')


def render_checklist(items: Sequence[str], key_prefix: str) -> None:
    """Render an interactive investigation checklist.

    Args:
        items: Checklist item labels.
        key_prefix: Unique prefix for Streamlit widget state keys.
    """
    for index, item in enumerate(items):
        st.checkbox(item, key=f"{key_prefix}_{index}")


def render_bullet_list(items: Iterable[str]) -> None:
    """Render a simple bulleted list using the shared visual style.

    Args:
        items: Bullet text items.
    """
    list_markup = "".join(f"<li>{escape(item)}</li>" for item in items)
    render_html_block(f'<ul class="soc-bullets">{list_markup}</ul>')


def render_integration_cards(integrations: Sequence[Mapping[str, str]]) -> None:
    """Render integration/platform availability cards.

    Args:
        integrations: Sequence of dicts with ``name``, ``category``, and ``status``.
    """
    status_class = {
        "Available": "available",
        "Available Soon": "soon",
    }
    cards = "".join(
        f"""
        <div class="soc-integration-card">
          <div class="soc-integration-name">{escape(str(item.get('name', '')))}</div>
          <div class="soc-integration-category">{escape(str(item.get('category', '')))}</div>
          <div class="soc-integration-status {status_class.get(str(item.get('status', '')), '')}">
            {escape(str(item.get('status', '')))}
          </div>
        </div>
        """
        for item in integrations
    )
    render_html_block(f'<div class="soc-integration-grid">{cards}</div>')


